<#
.SYNOPSIS
  Updates your local EduTrack project folder from the zip I delivered.

.DESCRIPTION
  SAFE BY DEFAULT: without -Apply it only PRINTS what it would change (dry run).
  With -Apply it will:
    1. back up your folder (excluding node_modules, .next, .git) to "<folder>-backup-<timestamp>"
    2. copy every file from the zip over your folder
       - it NEVER touches .env, .env.local or other .env.* files (your secrets)
       - it NEVER touches node_modules, .next or .git
    3. delete the few files that this update intentionally removed (listed below)
  It does not run git commands and does not install packages.

.EXAMPLE
  # 1) preview (changes nothing)
  powershell -ExecutionPolicy Bypass -File .\apply-update.ps1 `
    -Zip "$HOME\Downloads\school-main-r0-09.zip" `
    -Target "C:\Users\Administrator\Desktop\school-mainr0"

  # 2) really apply
  powershell -ExecutionPolicy Bypass -File .\apply-update.ps1 `
    -Zip "$HOME\Downloads\school-main-r0-09.zip" `
    -Target "C:\Users\Administrator\Desktop\school-mainr0" -Apply
#>
param(
  [Parameter(Mandatory = $true)][string]$Zip,
  [Parameter(Mandatory = $true)][string]$Target,
  [switch]$Apply
)

$ErrorActionPreference = 'Stop'

# Files/folders this update intentionally REMOVED (relative to the project root).
$ObsoleteItems = @(
  'proxy.ts',                       # dead on Next 14; replaced by src/middleware.ts
  'package-lock.json',              # pnpm is the only package manager (D10)
  'pnpm-workspace.yaml',            # placeholder file removed; settings live in package.json
  'public\mainfest.json',           # renamed to manifest.json
  'public\sw.js',                   # generated by next-pwa on every build (now git-ignored)
  'public\workbox-e9849328.js',     # generated by next-pwa on every build (now git-ignored)
  'src\app\api\test'                # leftover smoke-test route
)

function Fail($msg) { Write-Host "ERROR: $msg" -ForegroundColor Red; exit 1 }

# ---- checks -----------------------------------------------------------------------------
if (-not (Test-Path -LiteralPath $Zip -PathType Leaf)) { Fail "Zip not found: $Zip" }
if (-not (Test-Path -LiteralPath $Target -PathType Container)) { Fail "Target folder not found: $Target" }
if (-not (Test-Path -LiteralPath (Join-Path $Target 'package.json'))) {
  Fail "No package.json in $Target - this does not look like the project folder. Nothing was changed."
}
if (-not (Test-Path -LiteralPath (Join-Path $Target 'prisma\schema.prisma'))) {
  Fail "No prisma\schema.prisma in $Target - this does not look like the EduTrack project. Nothing was changed."
}

$Target = (Resolve-Path -LiteralPath $Target).Path.TrimEnd('\')
$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$temp = Join-Path ([System.IO.Path]::GetTempPath()) "edutrack-update-$stamp"
$backup = "$Target-backup-$stamp"

Write-Host ""
Write-Host "Zip    : $Zip"
Write-Host "Target : $Target"
Write-Host ("Mode   : " + $(if ($Apply) { 'APPLY (will change files)' } else { 'DRY RUN (changes nothing)' }))
Write-Host ""

# ---- extract zip to a temp folder ---------------------------------------------------------
New-Item -ItemType Directory -Path $temp | Out-Null
try {
  $tarOk = $false
  if (Get-Command tar.exe -ErrorAction SilentlyContinue) {
    & tar.exe -xf $Zip -C $temp 2>$null
    if ($LASTEXITCODE -eq 0) { $tarOk = $true }
  }
  if (-not $tarOk) { Expand-Archive -LiteralPath $Zip -DestinationPath $temp -Force }

  $src = Join-Path $temp 'school-main'
  if (-not (Test-Path -LiteralPath (Join-Path $src 'package.json'))) {
    Fail "The zip does not contain school-main\package.json. Nothing was changed."
  }

  # robocopy exit codes 0-7 mean success; 8 or more means failure.
  $excludeDirs = @('node_modules', '.next', '.git')
  $excludeFiles = @('.env', '.env.local', '.env.development', '.env.production', '.env.test', '.env.*.local')

  if (-not $Apply) {
    Write-Host "Files that WOULD be added or changed (robocopy list-only):" -ForegroundColor Cyan
    & robocopy $src $Target /E /L /NJH /NJS /NP /NDL /XD $excludeDirs /XF $excludeFiles | Out-Host
    Write-Host ""
    Write-Host "Items that WOULD be deleted (if present):" -ForegroundColor Cyan
    foreach ($item in $ObsoleteItems) {
      $p = Join-Path $Target $item
      if (Test-Path -LiteralPath $p) { Write-Host "  delete  $item" } else { Write-Host "  (absent) $item" -ForegroundColor DarkGray }
    }
    Write-Host ""
    Write-Host "Dry run only - nothing was changed. Re-run with -Apply to update." -ForegroundColor Yellow
    exit 0
  }

  # ---- 1) backup -------------------------------------------------------------------------
  Write-Host "Backing up to: $backup" -ForegroundColor Cyan
  & robocopy $Target $backup /E /NJH /NJS /NP /NFL /NDL /XD $excludeDirs | Out-Null
  if ($LASTEXITCODE -ge 8) { Fail "Backup failed (robocopy exit $LASTEXITCODE). Nothing was changed." }

  # ---- 2) copy ---------------------------------------------------------------------------
  Write-Host "Copying updated files..." -ForegroundColor Cyan
  & robocopy $src $Target /E /NJH /NJS /NP /NFL /NDL /XD $excludeDirs /XF $excludeFiles | Out-Null
  if ($LASTEXITCODE -ge 8) { Fail "Copy failed (robocopy exit $LASTEXITCODE). Your backup is at $backup" }

  # ---- 3) remove obsolete files ----------------------------------------------------------
  foreach ($item in $ObsoleteItems) {
    $p = Join-Path $Target $item
    if (Test-Path -LiteralPath $p) {
      Remove-Item -LiteralPath $p -Recurse -Force
      Write-Host "  removed $item"
    }
  }

  Write-Host ""
  Write-Host "Done. Backup of your previous files: $backup" -ForegroundColor Green
  Write-Host ""
  Write-Host "Next steps (in the project folder):" -ForegroundColor Cyan
  Write-Host "  npm install -g pnpm@10        # once, if 'pnpm -v' fails"
  Write-Host "  pnpm install --frozen-lockfile"
  Write-Host "  pnpm exec prisma generate"
  Write-Host "  pnpm typecheck"
  Write-Host "  pnpm test"
  Write-Host "  pnpm contract"
  Write-Host "  pnpm build"
  Write-Host ""
  Write-Host "If you use git: run 'git rm --cached public/sw.js public/workbox-*.js package-lock.json' then review 'git status'."
}
finally {
  if (Test-Path -LiteralPath $temp) { Remove-Item -LiteralPath $temp -Recurse -Force -ErrorAction SilentlyContinue }
}
